export const blogPost = (slug: string) =>
  blogPosts.find((post) => post.slug === slug);
export const blogReviewDate = (post: BlogPost) =>
  new Intl.DateTimeFormat('ka-GE', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
    timeZone: 'UTC',
  }).format(new Date(`${post.reviewedAt}T00:00:00Z`));
export const blogReadingMinutes = (post: BlogPost) =>
  Math.max(
    1,
    Math.ceil(
      [
        post.takeaway,
        ...post.sections.flatMap((section) => [
          section.title,
          ...section.paragraphs.map((paragraph) => paragraph.text),
          ...(section.checklist || []),
          ...(section.table
            ? [
                section.table.caption,
                ...section.table.rows.flat(),
                section.table.note,
              ]
            : []),
        ]),
      ]
        .join(' ')
        .split(/\s+/).length / 180,
    ),
  );
